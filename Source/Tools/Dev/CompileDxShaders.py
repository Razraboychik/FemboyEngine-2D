#!/usr/bin/env python3
"""Regenerates Source/Engine/RHI/Shaders/DxShaderBlobs.hpp with fxc bytecode.

Run after editing a d3d11/*.hlsl or d3d12/*.hlsl file. fxc comes from the
Windows SDK that ships with MSVC Build Tools; this is a developer tool, not a
runtime or setup dependency.
"""
from __future__ import annotations

import argparse
import os
import pathlib
import shutil
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[3]
SHADER_ROOT = ROOT / "Source" / "Engine" / "RHI" / "Shaders"
OUTPUT = SHADER_ROOT / "DxShaderBlobs.hpp"
NAMES = {
    "d3d11_sprite_VSMain": "D3D11SpriteVsSm5",
    "d3d11_sprite_PSMain": "D3D11SpritePsSm5",
    "d3d11_motion_VSMain": "D3D11MotionVsSm5",
    "d3d11_motion_PSMain": "D3D11MotionPsSm5",
    "d3d11_temporal_VSMain": "D3D11TemporalVsSm5",
    "d3d11_temporal_PSMain": "D3D11TemporalPsSm5",
    "d3d11_sharpen_PSMain": "D3D11SharpenPsSm5",
    "d3d12_sprite_VSMain": "D3D12SpriteVsSm5",
    "d3d12_sprite_PSMain": "D3D12SpritePsSm5",
    "d3d12_motion_VSMain": "D3D12MotionVsSm5",
    "d3d12_motion_PSMain": "D3D12MotionPsSm5",
    "d3d12_temporal_VSMain": "D3D12TemporalVsSm5",
    "d3d12_temporal_PSMain": "D3D12TemporalPsSm5",
    "d3d12_sharpen_VSMain": "D3D12SharpenVsSm5",
    "d3d12_sharpen_PSMain": "D3D12SharpenPsSm5",
}


def find_dxc() -> pathlib.Path:
    explicit = os.environ.get("FBY_DXC")
    if explicit:
        return pathlib.Path(explicit)
    found = shutil.which("dxc")
    if found:
        return pathlib.Path(found)
    sdk = os.environ.get("VULKAN_SDK")
    if sdk:
        candidate = pathlib.Path(sdk) / "Bin" / "dxc.exe"
        if candidate.is_file():
            return candidate
    raise SystemExit("dxc.exe not found; set FBY_DXC or VULKAN_SDK")


def find_fxc() -> pathlib.Path:
    explicit = os.environ.get("FBY_FXC")
    if explicit:
        return pathlib.Path(explicit)
    found = shutil.which("fxc")
    if found:
        return pathlib.Path(found)
    kits = pathlib.Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Windows Kits" / "10" / "bin"
    candidates = sorted(kits.glob("*/x64/fxc.exe"), reverse=True) if kits.exists() else []
    if candidates:
        return candidates[0]
    raise SystemExit("fxc.exe not found; set FBY_FXC or install the Windows SDK")


def compile_one(fxc: pathlib.Path, backend: str, name: str, entry: str, output: pathlib.Path) -> None:
    profile = "vs_5_0" if entry == "VSMain" else "ps_5_0"
    source = SHADER_ROOT / backend / f"{name}.hlsl"
    subprocess.run(
        [str(fxc), "/nologo", "/T", profile, "/E", entry, "/Fo", str(output), str(source)],
        check=True,
        stdout=subprocess.DEVNULL,
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fxc", default="")
    args = parser.parse_args()
    fxc = pathlib.Path(args.fxc) if args.fxc else find_fxc()
    with tempfile.TemporaryDirectory(prefix="fby-dx-shaders-") as temp:
        temp_dir = pathlib.Path(temp)
        for backend in ("d3d11", "d3d12"):
            names = ("sprite", "motion", "temporal", "sharpen")
            for name in names:
                entries = ("VSMain", "PSMain")
                if backend == "d3d11" and name == "sharpen":
                    entries = ("PSMain",)
                for entry in entries:
                    compile_one(fxc, backend, name, entry, temp_dir / f"{backend}_{name}_{entry}.cso")
        lines = [
            "// Generated by Source/Tools/Dev/CompileDxShaders.py; do not edit.",
            "#pragma once",
            "",
            "#include <array>",
            "#include <cstdint>",
            "",
            "namespace Fby::Rhi::Shaders::Dx",
            "{",
            "",
        ]
        dxc = find_dxc()
        material_vs = temp_dir / "material_sprite_vs.dxil"
        subprocess.run(
            [
                str(dxc),
                "-T",
                "vs_6_0",
                "-E",
                "VSMain",
                "-Fo",
                str(material_vs),
                str(SHADER_ROOT / "d3d12" / "material_sprite.hlsl"),
            ],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        for stem, symbol in NAMES.items():
            data = (temp_dir / f"{stem}.cso").read_bytes()
            lines.append(f"inline constexpr std::array<std::uint8_t, {len(data)}> {symbol}{{")
            for offset in range(0, len(data), 16):
                lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[offset : offset + 16]) + ",")
            lines.append("};")
            lines.append("")
        data = material_vs.read_bytes()
        lines.append(f"inline constexpr std::array<std::uint8_t, {len(data)}> D3D12MaterialSpriteVsDxil{{")
        for offset in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[offset : offset + 16]) + ",")
        lines.append("};")
        lines.append("")
        lines.append("}")
        OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
