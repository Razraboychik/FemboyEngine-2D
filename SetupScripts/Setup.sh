#!/usr/bin/env bash
# FemboyEngine 2.0 - one-click Linux dependency setup.
#
# Installs the pinned toolchain (CMake, Ninja, a C++26 compiler, Vulkan loader,
# glslang) and materialises the exact dependency sources into third_party/.
# CMake prefers those local checkouts, so a clean configure after this script
# needs no network access.
#
#   ./Setup.sh                  # all components
#   ./Setup.sh --component cpp  # C++ toolchain and pinned sources
#   ./Setup.sh --component archiver   # 7-Zip only
#   ./Setup.sh --component upscalers  # optional vendor SDKs
#   ./Setup.sh --skip-system    # sources only (CI image already has tools)
#   ./Setup.sh --force          # re-download every archive
#
# Versions validated by CI:
#   SDL3 release-3.4.18, Vulkan-Headers v1.4.366, glslang 15.3.0,
#   miniaudio 0.11.23, Box2D v3.2.0, Monocypher 4.0.2, LZMA SDK 25.01
#
# HarfBuzz 15.0.0 and SheenBidi 3.0.0 ship inside third_party/ and are not
# downloaded: the text pipeline links the vendored sources.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
THIRD_PARTY="${ROOT}/third_party"
DOWNLOADS="${ROOT}/build/_deps-download"
SKIP_SYSTEM=0
FORCE=0
COMPONENT=all
while [[ $# -gt 0 ]]; do
    case "$1" in
        --skip-system) SKIP_SYSTEM=1 ;;
        --force) FORCE=1 ;;
        --component) COMPONENT="${2:-}"; shift ;;
        --help|-h)
            sed -n '2,26p' "${BASH_SOURCE[0]}"
            exit 0
            ;;
        *)
            echo "unknown argument: $1" >&2
            exit 2
            ;;
    esac
    shift
done

case "${COMPONENT}" in
    all) RUN_CPP=1; RUN_ARCHIVER=1; RUN_UPSCALERS=1 ;;
    cpp) RUN_CPP=1; RUN_ARCHIVER=0; RUN_UPSCALERS=0 ;;
    archiver) RUN_CPP=0; RUN_ARCHIVER=1; RUN_UPSCALERS=0 ;;
    upscalers) RUN_CPP=0; RUN_ARCHIVER=0; RUN_UPSCALERS=1 ;;
    *)
        echo "unknown component: ${COMPONENT} (all, cpp, archiver, upscalers)" >&2
        exit 2
        ;;
esac

mkdir -p "${THIRD_PARTY}" "${DOWNLOADS}"
LOCK="${THIRD_PARTY}/dependencies.lock"
if [[ "${RUN_CPP}" -eq 1 ]]; then
    printf '# FemboyEngine pinned dependencies - generated by Setup.sh\n# version 1\ndate = %s\n' "$(date -Iseconds)" > "${LOCK}"
fi

log() { printf '\n==> %s\n' "$*"; }
warn() { printf 'WARN: %s\n' "$*" >&2; }

need() {
    if ! command -v "$1" >/dev/null 2>&1; then
        warn "$1 is missing"
        return 1
    fi
    return 0
}

download() {
    local url="$1" file="$2"
    local path="${DOWNLOADS}/${file}"
    if [[ -f "${path}" && "${FORCE}" -eq 0 ]]; then
        echo "  cached ${file}" >&2
    else
        echo "  downloading ${url}" >&2
        curl -fL --retry 3 --connect-timeout 20 -o "${path}" "${url}"
    fi
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "${path}" >> "${LOCK}"
    fi
    printf '%s\n' "${path}"
}

extract_tar() {
    local archive="$1" destination="$2"
    mkdir -p "${destination}"
    tar --strip-components=1 -xzf "${archive}" -C "${destination}"
}

install_system_linux() {
    if [[ "${SKIP_SYSTEM}" -eq 1 ]]; then
        return
    fi
    local CPP_APT="build-essential cmake ninja-build git curl ca-certificates pkg-config clang lld libvulkan-dev vulkan-tools glslang-tools libx11-dev libxext-dev libwayland-dev libxkbcommon-dev libdecor-0-dev libasound2-dev libpulse-dev"
    local ARCHIVER_APT="p7zip-full"
    local CPP_DNF="gcc-c++ cmake ninja-build git curl clang lld vulkan-loader-devel vulkan-tools glslang libX11-devel libXext-devel wayland-devel libxkbcommon-devel alsa-lib-devel pulseaudio-libs-devel"
    local ARCHIVER_DNF="p7zip"
    local CPP_PACMAN="base-devel cmake ninja git curl clang lld gcc vulkan-icd-loader vulkan-headers vulkan-tools glslang libx11 libxext wayland libxkbcommon alsa-lib libpulse"
    local ARCHIVER_PACMAN="p7zip"
    if command -v apt-get >/dev/null 2>&1; then
        log "APT packages"
        sudo apt-get update
        if [[ "${RUN_CPP}" -eq 1 ]]; then
            sudo apt-get install -y --no-install-recommends ${CPP_APT}
            if apt-cache show g++-16 >/dev/null 2>&1; then
                sudo apt-get install -y --no-install-recommends g++-16 gcc-16
            else
                warn "g++-16 is not packaged here; the distribution g++ is installed instead"
            fi
        fi
        if [[ "${RUN_ARCHIVER}" -eq 1 ]]; then
            sudo apt-get install -y --no-install-recommends ${ARCHIVER_APT}
        fi
    elif command -v dnf >/dev/null 2>&1; then
        log "DNF packages"
        if [[ "${RUN_CPP}" -eq 1 ]]; then
            sudo dnf install -y ${CPP_DNF}
            if ! sudo dnf install -y gcc-toolset-15-gcc-c++; then
                warn "gcc-toolset-15 is not packaged here; the distribution g++ is installed instead"
            fi
        fi
        if [[ "${RUN_ARCHIVER}" -eq 1 ]]; then
            sudo dnf install -y ${ARCHIVER_DNF}
        fi
    elif command -v pacman >/dev/null 2>&1; then
        log "pacman packages"
        if [[ "${RUN_CPP}" -eq 1 ]]; then
            sudo pacman -S --needed --noconfirm ${CPP_PACMAN}
        fi
        if [[ "${RUN_ARCHIVER}" -eq 1 ]]; then
            sudo pacman -S --needed --noconfirm ${ARCHIVER_PACMAN}
        fi
    else
        warn "unknown package manager; install the required packages manually"
    fi
}

install_system_macos() {
    if [[ "${SKIP_SYSTEM}" -eq 1 ]]; then
        return
    fi
    if ! command -v brew >/dev/null 2>&1; then
        warn "Homebrew is missing; install it from https://brew.sh then re-run"
        return
    fi
    log "Homebrew packages"
    brew update
    if [[ "${RUN_CPP}" -eq 1 ]]; then
        brew install cmake ninja git glslang vulkan-headers vulkan-loader molten-vk llvm gcc
    fi
    if [[ "${RUN_ARCHIVER}" -eq 1 ]]; then
        brew install p7zip
    fi
}

detect_system() {
    case "$(uname -s)" in
        Darwin) install_system_macos ;;
        Linux) install_system_linux ;;
        *) warn "unsupported platform $(uname -s)" ;;
    esac
}

detect_system
if [[ "${RUN_CPP}" -eq 1 ]]; then
log "Toolchain"
CMKE_OK=0
if need cmake; then
    CMAKE_VERSION="$(cmake --version | head -n1 | awk '{print $3}')"
    CMAKE_MAJOR="${CMAKE_VERSION%%.*}"
    if [[ "${CMAKE_MAJOR}" -lt 3 ]]; then
        warn "CMake ${CMAKE_VERSION} is too old; 3.28+ is required"
    else
        CMKE_OK=1
    fi
fi
need ninja || true
need git || true
if command -v clang++ >/dev/null 2>&1; then
    CLANG_VERSION="$(clang++ --version | head -n1)"
    CLANG_MAJOR="$(printf '%s\n' "${CLANG_VERSION}" | awk '{print $3}' | cut -d. -f1)"
    echo "  clang++ : ${CLANG_VERSION}"
    if [[ "${CLANG_MAJOR}" =~ ^[0-9]+$ ]] && [[ "${CLANG_MAJOR}" -lt 19 ]]; then
        warn "clang++ ${CLANG_MAJOR} is below the supported minimum 19"
    fi
    printf 'clang = %s\n' "${CLANG_VERSION}" >> "${LOCK}"
else
    warn "clang++ is missing; Clang 19+ is the validated toolchain"
fi
if command -v g++ >/dev/null 2>&1; then
    GCC_VERSION="$(g++ -dumpfullversion 2>/dev/null || g++ -dumpversion)"
    GCC_MAJOR="${GCC_VERSION%%.*}"
    echo "  g++     : ${GCC_VERSION}"
    if [[ "${GCC_MAJOR}" -lt 15 ]]; then
        warn "g++ ${GCC_MAJOR} is below the supported minimum 15"
    fi
    printf 'gcc = %s\n' "${GCC_VERSION}" >> "${LOCK}"
else
    warn "g++ is missing; GCC 16+ is the second-opinion toolchain"
fi
if [[ -n "${VULKAN_SDK:-}" ]]; then
    echo "  VULKAN_SDK=${VULKAN_SDK}"
    printf 'vulkan_sdk = %s\n' "${VULKAN_SDK}" >> "${LOCK}"
else
    warn "VULKAN_SDK is not set; Vulkan-Headers are still installed for the build"
fi

log "SDL3 release-3.4.18"
SDL_ARCHIVE="$(download "https://github.com/libsdl-org/SDL/archive/refs/tags/release-3.4.18.tar.gz" SDL3.tar.gz)"
extract_tar "${SDL_ARCHIVE}" "${THIRD_PARTY}/sdl3-src"
printf 'sdl3 = release-3.4.18\n' >> "${LOCK}"

log "Vulkan-Headers v1.4.366"
VK_ARCHIVE="$(download "https://github.com/KhronosGroup/Vulkan-Headers/archive/refs/tags/v1.4.366.tar.gz" Vulkan-Headers.tar.gz)"
extract_tar "${VK_ARCHIVE}" "${THIRD_PARTY}/vulkan-headers-src"
printf 'vulkan_headers = v1.4.366\n' >> "${LOCK}"

log "glslang 15.3.0"
GLSLANG_ARCHIVE="$(download "https://github.com/KhronosGroup/glslang/archive/refs/tags/15.3.0.tar.gz" glslang.tar.gz)"
extract_tar "${GLSLANG_ARCHIVE}" "${THIRD_PARTY}/glslang-src"
printf 'glslang = 15.3.0\n' >> "${LOCK}"

log "miniaudio 0.11.23"
MINIAUDIO_ARCHIVE="$(download "https://github.com/mackron/miniaudio/archive/refs/tags/0.11.23.tar.gz" miniaudio.tar.gz)"
extract_tar "${MINIAUDIO_ARCHIVE}" "${THIRD_PARTY}/miniaudio-master/miniaudio-master"
printf 'miniaudio = 0.11.23\n' >> "${LOCK}"

log "Box2D v3.2.0"
BOX2D_ARCHIVE="$(download "https://github.com/erincatto/box2d/archive/refs/tags/v3.2.0.tar.gz" box2d.tar.gz)"
extract_tar "${BOX2D_ARCHIVE}" "${THIRD_PARTY}/box2d-main/box2d-main"
printf 'box2d = v3.2.0\n' >> "${LOCK}"

log "RNNoise 0.1.1"
RNNOISE_ARCHIVE="$(download "https://github.com/xiph/rnnoise/archive/refs/tags/v0.1.1.tar.gz" rnnoise.tar.gz)"
RNNOISE_TEMP="${DOWNLOADS}/rnnoise"
rm -rf "${RNNOISE_TEMP}"
mkdir -p "${RNNOISE_TEMP}" "${THIRD_PARTY}/rnnoise"
tar -xzf "${RNNOISE_ARCHIVE}" -C "${RNNOISE_TEMP}"
cp -r "${RNNOISE_TEMP}/rnnoise-0.1.1/src" "${THIRD_PARTY}/rnnoise/"
cp -r "${RNNOISE_TEMP}/rnnoise-0.1.1/include" "${THIRD_PARTY}/rnnoise/"
cp -f "${RNNOISE_TEMP}/rnnoise-0.1.1/COPYING" "${THIRD_PARTY}/rnnoise/"
printf 'rnnoise = 0.1.1
' >> "${LOCK}"

log "Monocypher 4.0.2"
MONOCYPHER_ARCHIVE="$(download "https://github.com/LoupVaillant/Monocypher/archive/refs/tags/4.0.2.tar.gz" monocypher.tar.gz)"
MONOCYPHER_TEMP="${DOWNLOADS}/monocypher"
rm -rf "${MONOCYPHER_TEMP}"
mkdir -p "${MONOCYPHER_TEMP}" "${THIRD_PARTY}/monocypher"
tar -xzf "${MONOCYPHER_ARCHIVE}" -C "${MONOCYPHER_TEMP}"
cp -f "${MONOCYPHER_TEMP}/Monocypher-4.0.2/src/monocypher.h" "${THIRD_PARTY}/monocypher/"
cp -f "${MONOCYPHER_TEMP}/Monocypher-4.0.2/src/monocypher.c" "${THIRD_PARTY}/monocypher/"
cp -f "${MONOCYPHER_TEMP}/Monocypher-4.0.2/LICENCE.md" "${THIRD_PARTY}/monocypher/"
printf 'monocypher = 4.0.2\n' >> "${LOCK}"

log "LZMA SDK 25.01"
if command -v 7z >/dev/null 2>&1 || command -v 7za >/dev/null 2>&1; then
    LZMA_ARCHIVE="$(download "https://www.7-zip.org/a/lzma2501.7z" lzma.7z)"
    LZMA_TEMP="${DOWNLOADS}/lzma"
    rm -rf "${LZMA_TEMP}"
    mkdir -p "${LZMA_TEMP}" "${THIRD_PARTY}/lzma-sdk"
    (command -v 7z >/dev/null 2>&1 && 7z x -y -o"${LZMA_TEMP}" "${LZMA_ARCHIVE}") || \
        7za x -y -o"${LZMA_TEMP}" "${LZMA_ARCHIVE}"
    cp -f "${LZMA_TEMP}/C/"* "${THIRD_PARTY}/lzma-sdk/"
    printf 'lzma_sdk = 25.01\n' >> "${LOCK}"
else
    warn "7z is missing; skipping LZMA SDK (FemArchiver uses the FbyLZ fallback)"
fi

for required in \
    "third_party/entt-main/entt-main/src/entt/entt.hpp" \
    "third_party/tomlplusplus-master/tomlplusplus-master/toml.hpp" \
    "third_party/stb/stb_image.h" \
    "third_party/opus-master/opus-main/CMakeLists.txt" \
    "third_party/harfbuzz-download/harfbuzz-15.0.0/CMakeLists.txt" \
    "third_party/sheenbidi-download/SheenBidi-3.0.0/CMakeLists.txt" \
    "third_party/monocypher/monocypher.c" \n    "third_party/rnnoise/src/denoise.c"; do
    if [[ ! -e "${ROOT}/${required}" ]]; then
        warn "missing vendored dependency: ${required}"
    fi
done

fi

if [[ "${RUN_ARCHIVER}" -eq 1 ]]; then
    if command -v 7z >/dev/null 2>&1 || command -v 7za >/dev/null 2>&1; then
        log "Archiver ready"
    else
        warn "7-Zip is not installed; install p7zip or 7zip"
    fi
fi

if [[ "${RUN_UPSCALERS}" -eq 1 ]]; then
    "${ROOT}/SetupScripts/SetupUpscalers.sh" || warn "upscaler SDK setup skipped or incomplete"
fi

if [[ "${RUN_CPP}" -eq 1 ]]; then
log "Mobile toolchains"
MOBILE_MISSING=0
if [[ -z "${ANDROID_NDK_HOME:-}" && -z "${ANDROID_NDK_ROOT:-}" ]]; then
    echo "  Android: no NDK. Install Android Studio or set ANDROID_NDK_HOME to NDK r28c (28.2.13676358)"
    MOBILE_MISSING=1
else
    echo "  Android: NDK at ${ANDROID_NDK_HOME:-${ANDROID_NDK_ROOT}}"
fi
if command -v java >/dev/null 2>&1; then
    echo "  Android: JDK $(java -version 2>&1 | head -n 1)"
else
    echo "  Android: no JDK. Install OpenJDK 17 for the Gradle packaging step"
    MOBILE_MISSING=1
fi
echo "  iOS: needs macOS with Xcode 16 or newer; a Linux host cannot build the iOS target"
fi

log "Done"
echo "  configure   : cmake -S . -B build-dev -G Ninja -DCMAKE_BUILD_TYPE=RelWithDebInfo -DFBY_BUILD_TESTS=ON"
echo "  build       : cmake --build build-dev"
echo "  test        : ctest --test-dir build-dev --output-on-failure"
if [[ "${RUN_CPP}" -eq 1 && "${CMKE_OK}" -eq 0 ]]; then
    exit 1
fi
