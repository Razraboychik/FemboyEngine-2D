# FemboyEngine 2.0 - Windows dependency setup.
#
# Installs the pinned toolchain and sources into third_party/. CMake prefers the
# local checkouts (see cmake/FbyDependencies.cmake), so a clean configure after
# this script needs no network access.
#
#   powershell -ExecutionPolicy Bypass -File SetupScripts\SetupWindows.ps1
#   powershell -ExecutionPolicy Bypass -File SetupScripts\SetupWindows.ps1 -SkipSystem -Force
#
# Versions are the ones the CI slate validates:
#   Clang            19+ (clang-cl, the validated Windows toolchain)
#   GCC              15+ (MinGW-w64, second-opinion toolchain)
#   SDL3              release-3.4.18
#   Vulkan-Headers    v1.4.366
#   glslang           15.3.0
#   miniaudio         0.11.23
#   Box2D             v3.0.0
#   Monocypher        4.0.2
#   LZMA SDK          25.01
param(
    [switch]$SkipSystem,
    [switch]$Force
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$ThirdParty = Join-Path $Root "third_party"
$Downloads = Join-Path $Root "build\_deps-download"
New-Item -ItemType Directory -Force -Path $ThirdParty, $Downloads | Out-Null

$Versions = [ordered]@{
    SDL         = "release-3.4.18"
    Vulkan      = "v1.4.366"
    Glslang     = "15.3.0"
    Miniaudio   = "0.11.23"
    Box2D       = "v3.0.0"
    Monocypher  = "4.0.2"
    Rnnoise     = "0.1.1"
    LzmaSdk     = "25.01"
}

$Lock = [System.Collections.Generic.List[string]]::new()
$Lock.Add("# FemboyEngine pinned dependencies - generated by SetupScripts/SetupWindows.ps1")
$Lock.Add("# version 1")
$Lock.Add("date = $(Get-Date -Format o)")

function Write-Step([string]$Text) {
    Write-Host ""
    Write-Host "==> $Text" -ForegroundColor Magenta
}

function Ensure-Tool([string]$Name, [string]$WingetId) {
    $Found = Get-Command $Name -ErrorAction SilentlyContinue
    if ($null -ne $Found) {
        Write-Host "  $Name : $($Found.Source)"
        return $true
    }
    if ($SkipSystem -or [string]::IsNullOrEmpty($WingetId)) {
        Write-Warning "  $Name is missing. Install it manually or re-run without -SkipSystem."
        return $false
    }
    Write-Host "  installing $Name via winget ($WingetId)"
    winget install --id $WingetId --exact --silent --accept-source-agreements --accept-package-agreements
    # winget updates the machine/user PATH; this process still has the old one.
    $MachinePath = [Environment]::GetEnvironmentVariable("Path", "Machine")
    $UserPath = [Environment]::GetEnvironmentVariable("Path", "User")
    $env:Path = "$MachinePath;$UserPath"
    return $null -ne (Get-Command $Name -ErrorAction SilentlyContinue)
}

function Report-Compiler([string]$Name, [string]$VersionText, [int]$MinimumMajor) {
    if ([string]::IsNullOrWhiteSpace($VersionText)) {
        Write-Warning "  $Name version could not be read"
        return
    }
    $Major = 0
    if ($VersionText -match '(\d+)\.') {
        $Major = [int]$Matches[1]
    }
    Write-Host "  $Name : $VersionText"
    if ($Major -gt 0 -and $Major -lt $MinimumMajor) {
        Write-Warning "  $Name $Major is below the supported minimum $MinimumMajor"
    }
}

function Get-Archive([string]$Url, [string]$FileName) {
    $Path = Join-Path $Downloads $FileName
    if ((Test-Path $Path) -and -not $Force) {
        Write-Host "  cached $FileName"
    } else {
        Write-Host "  downloading $Url"
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $Path
    }
    $Hash = (Get-FileHash -Algorithm SHA256 -Path $Path).Hash.ToLowerInvariant()
    $Lock.Add("sha256 $FileName $Hash")
    return $Path
}

function Expand-Tar([string]$Archive, [string]$Destination, [bool]$Strip) {
    New-Item -ItemType Directory -Force -Path $Destination | Out-Null
    if ($Strip) {
        tar -xzf $Archive -C $Destination --strip-components=1
    } else {
        tar -xzf $Archive -C $Destination
    }
    if ($LASTEXITCODE -ne 0) {
        throw "tar failed for $Archive"
    }
}

Write-Step "Toolchain"
$HasCMake = Ensure-Tool "cmake" "Kitware.CMake"
$HasNinja = Ensure-Tool "ninja" "Ninja-build.Ninja"
$HasGit = Ensure-Tool "git" "Git.Git"
$Has7z = Ensure-Tool "7z" "7zip.7zip"
# Both compiler families are requirements: clang-cl is the validated build
# toolchain, GCC 15+ is the second opinion used by the portability checks.
$HasClang = Ensure-Tool "clang-cl" "LLVM.LLVM"
$HasGcc = Ensure-Tool "g++" "BrechtSanders.WinLibs.POSIX.UCRT"
if (-not ($HasCMake -and $HasNinja -and $HasGit)) {
    throw "cmake, ninja and git are required"
}
if ($HasClang) {
    $ClangVersion = (& clang-cl --version 2>$null | Select-Object -First 1)
    Report-Compiler "clang-cl" $ClangVersion 19
    $Lock.Add("clang = $ClangVersion")
} else {
    Write-Warning "clang-cl is missing. Install LLVM 19+ or re-run without -SkipSystem."
}
if ($HasGcc) {
    $GccVersion = (& g++ -dumpfullversion 2>$null)
    Report-Compiler "g++" $GccVersion 15
    $Lock.Add("gcc = $GccVersion")
} else {
    Write-Warning "g++ is missing. Install MinGW-w64 GCC 15+ or re-run without -SkipSystem."
}

Write-Step "Vulkan SDK"
if ($null -ne $env:VULKAN_SDK) {
    Write-Host "  VULKAN_SDK=$env:VULKAN_SDK"
    $Lock.Add("vulkan_sdk = $env:VULKAN_SDK")
} else {
    Write-Warning "  VULKAN_SDK is not set. The engine can build against Vulkan-Headers and will report a clean runtime error without a loader."
}

Write-Step "SDL3 $($Versions.SDL)"
$SdlArchive = Get-Archive "https://github.com/libsdl-org/SDL/archive/refs/tags/$($Versions.SDL).tar.gz" "SDL3.tar.gz"
Expand-Tar $SdlArchive (Join-Path $ThirdParty "sdl3-src") $true
$Lock.Add("sdl3 = $($Versions.SDL)")

Write-Step "Vulkan-Headers $($Versions.Vulkan)"
$VkArchive = Get-Archive "https://github.com/KhronosGroup/Vulkan-Headers/archive/refs/tags/$($Versions.Vulkan).tar.gz" "Vulkan-Headers.tar.gz"
Expand-Tar $VkArchive (Join-Path $ThirdParty "vulkan-headers-src") $true
$Lock.Add("vulkan_headers = $($Versions.Vulkan)")

Write-Step "glslang $($Versions.Glslang)"
$GlslangArchive = Get-Archive "https://github.com/KhronosGroup/glslang/archive/refs/tags/$($Versions.Glslang).tar.gz" "glslang.tar.gz"
Expand-Tar $GlslangArchive (Join-Path $ThirdParty "glslang-src") $true
$Lock.Add("glslang = $($Versions.Glslang)")

Write-Step "miniaudio $($Versions.Miniaudio)"
$MiniaudioArchive = Get-Archive "https://github.com/mackron/miniaudio/archive/refs/tags/$($Versions.Miniaudio).tar.gz" "miniaudio.tar.gz"
Expand-Tar $MiniaudioArchive (Join-Path $ThirdParty "miniaudio-master/miniaudio-master") $true
$Lock.Add("miniaudio = $($Versions.Miniaudio)")

Write-Step "Box2D $($Versions.Box2D)"
$Box2DArchive = Get-Archive "https://github.com/erincatto/box2d/archive/refs/tags/$($Versions.Box2D).tar.gz" "box2d.tar.gz"
Expand-Tar $Box2DArchive (Join-Path $ThirdParty "box2d-main/box2d-main") $true
$Lock.Add("box2d = $($Versions.Box2D)")

Write-Step "RNNoise $($Versions.Rnnoise)"
$RnnoiseArchive = Get-Archive "https://github.com/xiph/rnnoise/archive/refs/tags/v$($Versions.Rnnoise).tar.gz" "rnnoise.tar.gz"
$RnnoiseTemp = Join-Path $Downloads "rnnoise"
if (Test-Path $RnnoiseTemp) { Remove-Item -Recurse -Force $RnnoiseTemp }
New-Item -ItemType Directory -Force -Path $RnnoiseTemp | Out-Null
Expand-Tar $RnnoiseArchive $RnnoiseTemp $false
$RnnoiseDestination = Join-Path $ThirdParty "rnnoise"
New-Item -ItemType Directory -Force -Path $RnnoiseDestination | Out-Null
Copy-Item -Path (Join-Path $RnnoiseTemp "rnnoise-$($Versions.Rnnoise)/src") -Destination $RnnoiseDestination -Recurse -Force
Copy-Item -Path (Join-Path $RnnoiseTemp "rnnoise-$($Versions.Rnnoise)/include") -Destination $RnnoiseDestination -Recurse -Force
Copy-Item -Path (Join-Path $RnnoiseTemp "rnnoise-$($Versions.Rnnoise)/COPYING") -Destination $RnnoiseDestination -Force
$Lock.Add("rnnoise = $($Versions.Rnnoise)")

Write-Step "Monocypher $($Versions.Monocypher)"
$MonocypherArchive = Get-Archive "https://github.com/LoupVaillant/Monocypher/archive/refs/tags/$($Versions.Monocypher).tar.gz" "monocypher.tar.gz"
$MonocypherTemp = Join-Path $Downloads "monocypher"
if (Test-Path $MonocypherTemp) { Remove-Item -Recurse -Force $MonocypherTemp }
New-Item -ItemType Directory -Force -Path $MonocypherTemp | Out-Null
Expand-Tar $MonocypherArchive $MonocypherTemp $false
$MonocypherDestination = Join-Path $ThirdParty "monocypher"
New-Item -ItemType Directory -Force -Path $MonocypherDestination | Out-Null
Copy-Item -Path (Join-Path $MonocypherTemp "Monocypher-$($Versions.Monocypher)/src/monocypher.*") -Destination $MonocypherDestination -Force
Copy-Item -Path (Join-Path $MonocypherTemp "Monocypher-$($Versions.Monocypher)/LICENCE.md") -Destination $MonocypherDestination -Force
$Lock.Add("monocypher = $($Versions.Monocypher)")

Write-Step "LZMA SDK $($Versions.LzmaSdk)"
if ($Has7z) {
    $LzmaArchive = Get-Archive "https://www.7-zip.org/a/lzma$($Versions.LzmaSdk -replace '\.','').7z" "lzma.7z"
    $LzmaTemp = Join-Path $Downloads "lzma"
    if (Test-Path $LzmaTemp) { Remove-Item -Recurse -Force $LzmaTemp }
    New-Item -ItemType Directory -Force -Path $LzmaTemp | Out-Null
    7z x -y "-o$LzmaTemp" $LzmaArchive | Out-Null
    $LzmaDestination = Join-Path $ThirdParty "lzma-sdk"
    New-Item -ItemType Directory -Force -Path $LzmaDestination | Out-Null
    Copy-Item -Path (Join-Path $LzmaTemp "C\*") -Destination $LzmaDestination -Force
    $Lock.Add("lzma_sdk = $($Versions.LzmaSdk)")
} else {
    Write-Warning "  7z.exe is missing; skipping LZMA SDK. FemArchiver will use the FbyLZ fallback."
}

$Required = @(
    "third_party\entt-main\entt-main\src\entt\entt.hpp",
    "third_party\tomlplusplus-master\tomlplusplus-master\toml.hpp",
    "third_party\stb\stb_image.h",
    "third_party\opus-master\opus-main\CMakeLists.txt",
    "third_party\monocypher\monocypher.c",
    "third_party\harfbuzz-download\harfbuzz-15.0.0\CMakeLists.txt",
    "third_party\sheenbidi-download\SheenBidi-3.0.0\CMakeLists.txt",
    "third_party\rnnoise\src\denoise.c"
)
$Missing = @($Required | Where-Object { -not (Test-Path (Join-Path $Root $_)) })
if ($Missing.Count -gt 0) {
    Write-Warning "Vendored dependencies missing: $($Missing -join ', ')"
    Write-Warning "Clone the release tag or copy them into third_party before configuring."
}

$LockPath = Join-Path $ThirdParty "dependencies.lock"
$Lock | Set-Content -Encoding UTF8 $LockPath

Write-Step "Mobile toolchains"
$NdkHome = $env:ANDROID_NDK_HOME
if (-not $NdkHome) { $NdkHome = $env:ANDROID_NDK_ROOT }
if ($NdkHome) {
    Write-Host "  Android: NDK at $NdkHome"
} else {
    Write-Warning "  Android: no NDK. Install Android Studio and set ANDROID_NDK_HOME to NDK r28c (28.2.13676358)."
}
$Java = Get-Command java -ErrorAction SilentlyContinue
if ($Java) {
    Write-Host "  Android: JDK $((& java -version 2>&1 | Select-Object -First 1))"
} else {
    Write-Warning "  Android: no JDK. Install OpenJDK 17 for the Gradle packaging step."
}
Write-Host "  iOS: needs macOS with Xcode 16 or newer; a Windows host cannot build the iOS target."

Write-Step "Done"
Write-Host "  pinned lock : $LockPath"
Write-Host "  clang-cl    : validated toolchain for the default build"
Write-Host "  g++         : second-opinion toolchain (GCC 15+)"
Write-Host "  configure   : cmake -S . -B build -G Ninja -DCMAKE_BUILD_TYPE=RelWithDebInfo -DFBY_BUILD_TESTS=ON"
Write-Host "  build       : cmake --build build"
Write-Host "  test        : ctest --test-dir build --output-on-failure"
