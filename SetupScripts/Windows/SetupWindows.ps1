# FemboyEngine 2.0 - Windows dependency setup.
#
# Installs the pinned toolchain and sources into third_party/. CMake prefers the
# local checkouts (see cmake/FbyDependencies.cmake), so a clean configure after
# this script needs no network access.
#
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1 -SkipSystem -Force
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1 -Component Cpp
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1 -Component Archiver
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1 -Component Upscalers
#   powershell -ExecutionPolicy Bypass -File SetupScripts\Windows\SetupWindows.ps1 -WithVendorSdks -AcceptVendorLicenses
#
# Versions are the ones the CI slate validates:
#   LLVM             23.1.4 (clang-cl, the validated Windows toolchain)
#   GCC              15+ (MinGW-w64, second-opinion toolchain)
#   SDL3              release-3.4.18
#   Vulkan-Headers    v1.4.366
#   glslang           15.3.0
#   miniaudio         0.11.23
#   Box2D             v3.2.0
#   Monocypher        4.0.2
#   LZMA SDK          25.01
param(
    [switch]$SkipSystem,
    [switch]$Force,
    [switch]$WithVendorSdks,
    [switch]$AcceptVendorLicenses,
    [ValidateSet("All", "Cpp", "Archiver", "Upscalers")]
    [string]$Component = "All"
)

$ErrorActionPreference = "Stop"
$Root = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot "..\.."))
$ThirdParty = Join-Path $Root "third_party"
$Downloads = Join-Path $Root "build\_deps-download"
New-Item -ItemType Directory -Force -Path $ThirdParty, $Downloads | Out-Null

$Versions = [ordered]@{
    Llvm        = "23.1.4"
    SDL         = "release-3.4.18"
    Vulkan      = "v1.4.366"
    Glslang     = "15.3.0"
    Miniaudio   = "0.11.23"
    Box2D       = "v3.2.0"
    Monocypher  = "4.0.2"
    Rnnoise     = "0.1.1"
    LzmaSdk     = "25.01"
}

$Lock = [System.Collections.Generic.List[string]]::new()
$Lock.Add("# FemboyEngine pinned dependencies - generated by SetupScripts/Windows/SetupWindows.ps1")
$Lock.Add("# version 1")
$Lock.Add("date = $(Get-Date -Format o)")

function Write-Step([string]$Text) {
    Write-Host ""
    Write-Host "==> $Text" -ForegroundColor Magenta
}

function Invoke-VendorSetup {
    $DlssRoot = if ($env:FBY_DLSS_ROOT) { $env:FBY_DLSS_ROOT } else { Join-Path $ThirdParty "dlss" }
    $FidelityFxRepo = if ($env:FBY_FIDELITYFX_REPO) { $env:FBY_FIDELITYFX_REPO } else { Join-Path $ThirdParty "fidelityfx" }
    $FidelityFxRoot = if ($env:FBY_FIDELITYFX_ROOT) { $env:FBY_FIDELITYFX_ROOT } else { Join-Path $FidelityFxRepo "Kits\FidelityFX" }
    $XessRoot = if ($env:FBY_XESS_ROOT) { $env:FBY_XESS_ROOT } else { Join-Path $ThirdParty "xess" }

    function Clone-Sdk([string]$Url, [string]$Destination) {
        if (Test-Path (Join-Path $Destination ".git")) {
            Write-Host "  present $Destination"
            return
        }
        Write-Host "  cloning $Url"
        git clone --depth 1 $Url $Destination
    }

    if ($WithVendorSdks) {
        if (-not $AcceptVendorLicenses) {
            Write-Warning "Vendor SDKs requested without -AcceptVendorLicenses; review the license and re-run"
            return
        }
        if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
            Write-Warning "git is required to download vendor SDKs"
            return
        }
        Write-Step "Vendor SDK license notice"
        Write-Host "NVIDIA DLSS SDK: NVIDIA RTX SDKs License."
        Write-Host "AMD FidelityFX SDK: AMD FidelityFX license."
        Write-Host "Intel XeSS SDK: Intel Simplified Software License."
        Clone-Sdk "https://github.com/NVIDIA/DLSS.git" $DlssRoot
        Clone-Sdk "https://github.com/GPUOpen-LibrariesAndSDKs/FidelityFX-SDK.git" $FidelityFxRepo
        Clone-Sdk "https://github.com/intel/xess.git" $XessRoot
    }

    Write-Step "SDK layout"
    $Missing = 0
    if (Test-Path (Join-Path $DlssRoot "include\nvsdk_ngx.h")) { Write-Host "  DLSS       : $DlssRoot" }
    else { Write-Warning "DLSS not found at $DlssRoot"; $Missing++ }
    if (Test-Path (Join-Path $FidelityFxRoot "api\include\ffx_api.h")) { Write-Host "  FidelityFX : $FidelityFxRoot" }
    else { Write-Warning "FidelityFX not found at $FidelityFxRoot"; $Missing++ }
    if (Test-Path (Join-Path $XessRoot "inc\xess\xess.h")) { Write-Host "  XeSS       : $XessRoot" }
    else { Write-Warning "XeSS not found at $XessRoot" }
    if ($Missing -eq 0) {
        Write-Host "  CMake: -DFBY_WITH_DLSS=ON -DFBY_DLSS_ROOT=`"$DlssRoot`""
        Write-Host "  CMake: -DFBY_WITH_FIDELITYFX=ON -DFBY_FIDELITYFX_ROOT=`"$FidelityFxRoot`""
    }
}

function Ensure-Tool([string]$Name, [string]$WingetId) {
    $Found = Get-Command $Name -ErrorAction SilentlyContinue
    if ($null -ne $Found) {
        Write-Host "  $Name : $($Found.Source)"
        return $true
    }
    if ($SkipSystem -or [string]::IsNullOrEmpty($WingetId)) {
        Write-Warning "  $Name is missing. Install it manually or re-run without -SkipSystem."
        return $false
    }
    Write-Host "  installing $Name via winget ($WingetId)"
    winget install --id $WingetId --exact --silent --accept-source-agreements --accept-package-agreements
    # winget updates the machine/user PATH; this process still has the old one.
    $MachinePath = [Environment]::GetEnvironmentVariable("Path", "Machine")
    $UserPath = [Environment]::GetEnvironmentVariable("Path", "User")
    $env:Path = "$MachinePath;$UserPath"
    return $null -ne (Get-Command $Name -ErrorAction SilentlyContinue)
}

function Get-ClangVersion {
    $Command = Get-Command clang-cl -ErrorAction SilentlyContinue
    if ($null -eq $Command) {
        return $null
    }
    return (& $Command.Source --version 2>$null | Select-Object -First 1)
}

function Ensure-Llvm {
    $VersionText = Get-ClangVersion
    if ($null -ne $VersionText -and $VersionText -match [regex]::Escape($Versions.Llvm)) {
        Write-Host "  clang-cl : $VersionText"
        return $true
    }
    if ($SkipSystem) {
        Write-Warning "  clang-cl $($Versions.Llvm) is expected; found '$VersionText'. Continuing because -SkipSystem is set."
        return $null -ne $VersionText
    }
    $Installer = Join-Path $Downloads "LLVM-$($Versions.Llvm)-win64.msi"
    if ($Force -or -not (Test-Path $Installer)) {
        $Url = "https://github.com/llvm/llvm-project/releases/download/llvmorg-$($Versions.Llvm)/LLVM-$($Versions.Llvm)-win64.msi"
        Write-Host "  downloading LLVM $($Versions.Llvm)"
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $Installer
    }
    Write-Host "  installing LLVM $($Versions.Llvm)"
    $Process = Start-Process msiexec.exe -Wait -PassThru -ArgumentList @(
        "/i", "`"$Installer`"", "/qn", "/norestart", "ALLUSERS=1"
    )
    if ($Process.ExitCode -ne 0) {
        throw "LLVM installer failed with exit code $($Process.ExitCode)"
    }
    $env:Path = "C:\Program Files\LLVM\bin;$env:Path"
    $VersionText = Get-ClangVersion
    if ($null -eq $VersionText -or $VersionText -notmatch [regex]::Escape($Versions.Llvm)) {
        throw "LLVM $($Versions.Llvm) was installed, but clang-cl reports '$VersionText'"
    }
    Write-Host "  clang-cl : $VersionText"
    return $true
}

function Report-Compiler([string]$Name, [string]$VersionText, [int]$MinimumMajor) {
    if ([string]::IsNullOrWhiteSpace($VersionText)) {
        Write-Warning "  $Name version could not be read"
        return
    }
    $Major = 0
    if ($VersionText -match '(\d+)\.') {
        $Major = [int]$Matches[1]
    }
    Write-Host "  $Name : $VersionText"
    if ($Major -gt 0 -and $Major -lt $MinimumMajor) {
        Write-Warning "  $Name $Major is below the supported minimum $MinimumMajor"
    }
}

if ($Component -eq "Upscalers") {
    Invoke-VendorSetup
    exit 0
}
if ($Component -eq "Archiver") {
    Write-Step "7-Zip"
    $Has7z = Ensure-Tool "7z" "7zip.7zip"
    if (-not $Has7z) {
        Write-Error "7-Zip is required for the archiver component."
        exit 1
    }
    Write-Host " 7-Zip is ready."
    exit 0
}

function Get-Archive([string]$Url, [string]$FileName) {
    $Path = Join-Path $Downloads $FileName
    if ((Test-Path $Path) -and -not $Force) {
        Write-Host "  cached $FileName"
    } else {
        Write-Host "  downloading $Url"
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile $Path
    }
    $Hash = (Get-FileHash -Algorithm SHA256 -Path $Path).Hash.ToLowerInvariant()
    $Lock.Add("sha256 $FileName $Hash")
    return $Path
}

function Expand-Tar([string]$Archive, [string]$Destination, [bool]$Strip) {
    New-Item -ItemType Directory -Force -Path $Destination | Out-Null
    if ($Strip) {
        tar -xzf $Archive -C $Destination --strip-components=1
    } else {
        tar -xzf $Archive -C $Destination
    }
    if ($LASTEXITCODE -ne 0) {
        throw "tar failed for $Archive"
    }
}

Write-Step "Toolchain"
$HasCMake = Ensure-Tool "cmake" "Kitware.CMake"
$HasNinja = Ensure-Tool "ninja" "Ninja-build.Ninja"
$HasGit = Ensure-Tool "git" "Git.Git"
$Has7z = if ($Component -eq "All") {
    Ensure-Tool "7z" "7zip.7zip"
} else {
    $null -ne (Get-Command "7z" -ErrorAction SilentlyContinue)
}
# Both compiler families are requirements: clang-cl is the validated build
# toolchain, GCC 16+ is the second opinion used by the portability checks.
$HasClang = Ensure-Llvm
$HasGcc = Ensure-Tool "g++" "BrechtSanders.WinLibs.POSIX.UCRT"
if (-not ($HasCMake -and $HasNinja -and $HasGit)) {
    throw "cmake, ninja and git are required"
}
if ($HasClang) {
    $ClangVersion = (& clang-cl --version 2>$null | Select-Object -First 1)
    Report-Compiler "clang-cl" $ClangVersion 19
    $Lock.Add("clang = $ClangVersion")
} else {
    Write-Warning "clang-cl is missing. Install LLVM 19+ or re-run without -SkipSystem."
}
if ($HasGcc) {
    $GccVersion = (& g++ -dumpfullversion 2>$null)
    Report-Compiler "g++" $GccVersion 16
    $Lock.Add("gcc = $GccVersion")
} else {
    Write-Warning "g++ is missing. Install MinGW-w64 GCC 16+ or re-run without -SkipSystem."
}

Write-Step "Vulkan SDK"
if ($null -ne $env:VULKAN_SDK) {
    Write-Host "  VULKAN_SDK=$env:VULKAN_SDK"
    $Lock.Add("vulkan_sdk = $env:VULKAN_SDK")
} else {
    Write-Warning "  VULKAN_SDK is not set. The engine can build against Vulkan-Headers and will report a clean runtime error without a loader."
}

